"use client";

import { useState, useEffect, useRef, useCallback } from "react";
import {
  buildPollinationsUrl,
  generateFreeImage,
  loadFreeHistory,
  saveFreeHistory,
  secondsUntilFreeAllowed,
  FREE_ASPECTS,
  POLLINATIONS_LAST_GENERATED_KEY,
} from "../pollinations.js";

async function downloadBlob(blob, filename) {
  const blobUrl = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = blobUrl;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  setTimeout(() => URL.revokeObjectURL(blobUrl), 5000);
}

// Free Image Studio — Magic Higgsfield Studio, $0 mode.
// No API key. Images are generated by Pollinations (Flux, free/unlimited)
// via a direct browser call. No key is stored, no paid API is called.
export default function FreeImageStudio() {
  const [prompt, setPrompt] = useState("");
  const [aspectId, setAspectId] = useState("1:1");
  const [seed, setSeed] = useState(() => Math.floor(Math.random() * 1000000));
  const [lockSeed, setLockSeed] = useState(false);
  const [generating, setGenerating] = useState(false);
  const [generateError, setGenerateError] = useState(null);
  const [currentUrl, setCurrentUrl] = useState(null);
  const [currentBlob, setCurrentBlob] = useState(null);
  const [history, setHistory] = useState([]);
  const [waitSeconds, setWaitSeconds] = useState(0);
  const textareaRef = useRef(null);

  useEffect(() => {
    setHistory(loadFreeHistory());
    const last = Number(localStorage.getItem(POLLINATIONS_LAST_GENERATED_KEY) || 0);
    setWaitSeconds(secondsUntilFreeAllowed(last));
  }, []);

  useEffect(() => {
    if (waitSeconds <= 0) return;
    const t = setTimeout(() => setWaitSeconds((s) => Math.max(0, s - 1)), 1000);
    return () => clearTimeout(t);
  }, [waitSeconds]);

  const aspect = FREE_ASPECTS.find((a) => a.id === aspectId) || FREE_ASPECTS[0];

  const handleGenerate = useCallback(async () => {
    if (generating) return;
    if (!prompt.trim()) { setGenerateError("Please enter a prompt first."); return; }
    const wait = secondsUntilFreeAllowed(Number(localStorage.getItem(POLLINATIONS_LAST_GENERATED_KEY) || 0));
    if (wait > 0) { setGenerateError(`Free limit: 1 new image per ~45s. Please wait ${wait}s.`); setWaitSeconds(wait); return; }

    setGenerating(true);
    setGenerateError(null);
    const useSeed = lockSeed ? seed : Math.floor(Math.random() * 1000000);
    if (!lockSeed) setSeed(useSeed);
    try {
      const { url, blob } = await generateFreeImage({
        prompt: prompt.trim(), width: aspect.width, height: aspect.height, seed: useSeed, model: 'flux',
      });
      localStorage.setItem(POLLINATIONS_LAST_GENERATED_KEY, String(Date.now()));
      setWaitSeconds(45);
      setCurrentUrl(url);
      setCurrentBlob(blob);
      const entry = { id: String(Date.now()), url, prompt: prompt.trim(), model: 'flux (free)', aspect_ratio: aspect.id, seed: useSeed, timestamp: new Date().toISOString() };
      setHistory(saveFreeHistory(entry));
    } catch (e) {
      console.error("[FreeImageStudio] Generation failed:", e);
      setGenerateError(e.message.slice(0, 160));
    } finally {
      setGenerating(false);
    }
  }, [generating, prompt, aspect, seed, lockSeed]);

  const handleDownload = async () => {
    if (currentBlob) { await downloadBlob(currentBlob, `magic-higgsfield-free-${seed}.jpg`); return; }
    if (currentUrl) window.open(currentUrl, "_blank");
  };

  const previewUrl = currentUrl || (prompt.trim() ? buildPollinationsUrl(prompt.trim(), { width: aspect.width, height: aspect.height, seed }) : null);

  return (
    <div className="w-full h-full flex flex-col items-center justify-center bg-app-bg relative p-4 md:p-6 overflow-y-auto custom-scrollbar overflow-x-hidden">
      <div className="flex flex-col items-center mb-8 animate-fade-in-up">
        <span className="text-xs font-black tracking-widest uppercase bg-primary text-black px-3 py-1 rounded-full mb-4">Free — No API key needed</span>
        <h1 className="text-2xl sm:text-4xl md:text-6xl font-black text-white tracking-widest uppercase mb-3 text-center px-4">Free Image Studio</h1>
        <p className="text-secondary text-sm font-medium tracking-wide opacity-60 text-center px-4">
          Flux images via Pollinations — free, unlimited. 1 new image per ~45s per visitor.
          Premium models (Kie / Muapi) are optional under Premium.
        </p>
      </div>

      <div className="w-full max-w-4xl relative z-40">
        <div className="w-full bg-[#111]/90 backdrop-blur-xl border border-white/10 rounded-[2rem] p-4 md:p-5 flex flex-col gap-4 shadow-3xl">
          <textarea
            ref={textareaRef}
            value={prompt}
            onChange={(e) => setPrompt(e.target.value)}
            placeholder="Describe the image you want — e.g. a sunlit Dubai garden with drip irrigation, photorealistic"
            rows={3}
            className="w-full bg-transparent border-none text-white text-base md:text-lg placeholder:text-muted focus:outline-none resize-none leading-relaxed"
          />
          <div className="flex flex-wrap items-center gap-2">
            {FREE_ASPECTS.map((a) => (
              <button key={a.id} type="button" onClick={() => setAspectId(a.id)}
                className={`px-3 py-2 rounded-xl text-xs font-bold border transition-all ${aspectId === a.id ? 'bg-primary text-black border-primary' : 'bg-white/5 text-white border-white/10 hover:bg-white/10'}`}>
                {a.label}
              </button>
            ))}
            <label className="ml-2 flex items-center gap-2 text-xs text-white/60">
              <input type="checkbox" checked={lockSeed} onChange={(e) => setLockSeed(e.target.checked)} /> Lock seed ({seed})
            </label>
            {!lockSeed && (
              <button type="button" onClick={() => setSeed(Math.floor(Math.random() * 1000000))} className="px-3 py-2 rounded-xl text-xs font-bold bg-white/5 text-white border border-white/10">🎲 New seed</button>
            )}
          </div>
          <button type="button" onClick={handleGenerate} disabled={generating || waitSeconds > 0}
            className="bg-primary text-black px-8 py-3.5 rounded-2xl font-black text-base hover:shadow-glow hover:scale-[1.02] active:scale-95 transition-all disabled:opacity-60 disabled:cursor-not-allowed">
            {generating ? "Generating… (free, ~6s)" : waitSeconds > 0 ? `Free limit — wait ${waitSeconds}s` : "Generate Free ✨"}
          </button>
          {generateError && <p className="text-red-400 text-sm text-center">{generateError}</p>}
          {previewUrl && !currentUrl && <p className="text-white/40 text-xs text-center">Preview URL ready — press Generate. Pollinations may return a smaller size than requested.</p>}
        </div>
      </div>

      {currentUrl && (
        <div className="mt-8 flex flex-col items-center gap-4">
          <img src={currentUrl} alt={prompt} className="max-h-[55vh] max-w-[85vw] rounded-3xl shadow-3xl border border-white/10 object-contain" />
          <div className="flex gap-3">
            <button type="button" onClick={handleDownload} className="bg-primary text-black px-6 py-2.5 rounded-2xl text-xs font-bold">↓ Download</button>
            <button type="button" onClick={() => { setCurrentUrl(null); setCurrentBlob(null); setPrompt(""); }} className="bg-white/10 hover:bg-white/20 px-6 py-2.5 rounded-2xl text-xs font-bold text-white border border-white/5">+ New</button>
          </div>
        </div>
      )}

      {history.length > 0 && (
        <div className="mt-10 w-full max-w-4xl">
          <h2 className="text-white/60 text-xs font-bold uppercase tracking-widest mb-3">Your free history (this browser only)</h2>
          <div className="grid grid-cols-3 sm:grid-cols-5 gap-3">
            {history.map((entry) => (
              <button key={entry.id} type="button" onClick={() => setCurrentUrl(entry.url)}
                className="rounded-xl overflow-hidden border border-white/10 hover:border-primary/50 transition-all">
                <img src={entry.url} alt={entry.prompt} className="w-full aspect-square object-cover" loading="lazy" />
              </button>
            ))}
          </div>
        </div>
      )}
    </div>
  );
}
